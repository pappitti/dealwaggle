#!/usr/bin/env node
// Generates tokens/tokens.css and tokens/tailwind-theme.css from tokens/tokens.json.
// No dependencies. Run from anywhere: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8"));
const HEADER = "/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n";

// Token leaves are objects with $value; group keys starting with $ are metadata.
const entries = (group) => Object.entries(group).filter(([k]) => !k.startsWith("$"));
const lookup = (path) => path.split(".").reduce((node, key) => node?.[key], tokens);
const ident = (key) => String(key).replace(".", "-");

// A reference to a primitive colour becomes var(--dw-<family>-<step>) so overriding a primitive cascades.
const cssValue = (value) => {
  const ref = typeof value === "string" && value.match(/^\{(.+)\}$/);
  if (!ref) return value;
  const [group, ...rest] = ref[1].split(".");
  if (group === "color") return `var(--dw-${rest.join("-")})`;
  if (group === "font" && rest[0] === "family") return `var(--dw-font-${rest[1]})`;
  return cssValue(lookup(ref[1]).$value);
};
// Quote family names with spaces; keywords like system-ui and -apple-system must stay bare.
const fontStack = (list) => list.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");

const lines = [];
const section = (title) => lines.push(`\n  /* ${title} */`);
const decl = (name, value) => lines.push(`  --dw-${name}: ${value};`);

section("Colour primitives");
for (const [family, scale] of entries(tokens.color)) for (const [step, t] of entries(scale)) decl(`${family}-${step}`, t.$value);

section("Fonts");
for (const [name, t] of entries(tokens.font.family)) decl(`font-${name}`, fontStack(t.$value));
for (const [name, t] of entries(tokens.font.weight)) decl(`weight-${name}`, t.$value);

section("Text styles: use as font: var(--dw-type-body); letter-spacing: var(--dw-type-body-tracking)");
for (const [name, t] of entries(tokens.type)) {
  const v = t.$value;
  decl(`type-${name}`, `${v.fontWeight} ${v.fontSize}/${v.lineHeight} ${cssValue(v.fontFamily)}`);
  decl(`type-${name}-tracking`, v.letterSpacing);
}

section("Spacing (4px grid)");
for (const [name, t] of entries(tokens.space)) decl(`space-${ident(name)}`, t.$value);
section("Radii");
for (const [name, t] of entries(tokens.radius)) decl(`radius-${name}`, t.$value);
section("Sizes");
for (const [name, t] of entries(tokens.size)) decl(`size-${name}`, t.$value);
section("Motion");
for (const [name, t] of entries(tokens.duration)) decl(`duration-${name}`, t.$value);
for (const [name, t] of entries(tokens.easing)) decl(`ease-${name}`, `cubic-bezier(${t.$value.join(", ")})`);
section("Layers");
for (const [name, t] of entries(tokens.z)) decl(`z-${name}`, t.$value);

const themeBlock = (mode) => [
  ...entries(tokens.theme[mode]).map(([name, t]) => `  --dw-${name}: ${cssValue(t.$value)};`),
  ...entries(tokens.shadow[mode]).map(([name, t]) => `  --dw-shadow-${name}: ${t.$value};`),
  `  color-scheme: ${mode};`,
].join("\n");

const css = `${HEADER}
:root {${lines.join("\n")}

  /* Semantic colours and shadows: light */
${themeBlock("light")}
}

/* Dark: follows the OS unless the page sets data-theme="light" (or class "light"). */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]):not(.light) {
${themeBlock("dark").replace(/^/gm, "  ")}
  }
}
:root[data-theme="dark"], :root.dark {
${themeBlock("dark")}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --dw-duration-instant: 0ms;
    --dw-duration-fast: 0ms;
    --dw-duration-base: 0ms;
    --dw-duration-slow: 0ms;
  }
}
`;
writeFileSync(join(root, "tokens/tokens.css"), css);

// Tailwind v4: utilities read the CSS variables, so themes switch without dark: variants.
const tw = [];
const twd = (name, value) => tw.push(`  --${name}: ${value};`);
tw.push("  /* Only DealWaggle colours exist: off-brand classes like bg-blue-500 will not compile. */");
twd("color-*", "initial");
twd("color-white", "#fff");
twd("color-black", "#000");
twd("color-transparent", "transparent");
twd("color-current", "currentColor");
for (const [family, scale] of entries(tokens.color)) for (const [step] of entries(scale)) twd(`color-${family}-${step}`, `var(--dw-${family}-${step})`);
tw.push("\n  /* Semantic colours: bg-surface, text-fg-muted, border-line, bg-accent, text-accent-fg ... */");
const twName = { text: "fg", "text-muted": "fg-muted", "text-subtle": "fg-subtle", border: "line", "border-strong": "line-strong", "border-input": "line-input", "accent-text": "accent-fg", "positive-text": "positive-fg", "caution-text": "caution-fg", "critical-text": "critical-fg", "info-text": "info-fg", "inverse-bg": "inverse", "inverse-text": "inverse-fg" };
for (const [name] of entries(tokens.theme.light)) twd(`color-${twName[name] ?? name}`, `var(--dw-${name})`);
tw.push("\n  /* Fonts and text styles: font-display, text-title-1, text-body ... */");
for (const [name] of entries(tokens.font.family)) twd(`font-${name}`, `var(--dw-font-${name})`);
for (const [name, t] of entries(tokens.type)) {
  const v = t.$value;
  twd(`text-${name}`, v.fontSize);
  twd(`text-${name}--line-height`, v.lineHeight);
  twd(`text-${name}--letter-spacing`, v.letterSpacing);
  twd(`text-${name}--font-weight`, String(v.fontWeight));
}
tw.push("\n  /* Radii, shadows, easing */");
for (const [name] of entries(tokens.radius)) twd(`radius-${name}`, `var(--dw-radius-${name})`);
for (const [name] of entries(tokens.shadow.light)) twd(`shadow-${name}`, `var(--dw-shadow-${name})`);
for (const [name] of entries(tokens.easing)) twd(`ease-${name}`, `var(--dw-ease-${name})`);

writeFileSync(
  join(root, "tokens/tailwind-theme.css"),
  `${HEADER}/* Tailwind CSS v4. In your main stylesheet:
     @import "tailwindcss";
     @import "./design-system/dealwaggle.css";
     @import "./design-system/tokens/tailwind-theme.css";
   Spacing needs nothing: Tailwind's default 4px step already matches the DealWaggle grid. */

@theme inline {
${tw.join("\n")}
}
`,
);
console.log("Wrote tokens/tokens.css and tokens/tailwind-theme.css");
